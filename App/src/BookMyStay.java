/**
 * UseCase1HotelBookingApp
 *
 * This class represents the entry point of the Hotel Booking application.
 * It demonstrates how a Java program starts execution and prints
 * a welcome message to the console.
 *
 * The program displays the application name and version information.
 * Execution begins from the main() method and follows a simple linear flow.
 *
 * @author Sunishka
 * @version 1.0
 */

public class BookMyStay {

    /**
     * Main method - Entry point of the application
     * JVM starts execution from this method
     */
    public static void main(String[] args) {

        // Display welcome message
        System.out.println("======================================");
        System.out.println("   Welcome to Hotel Booking System");
        System.out.println("======================================");

        // Display application details
        System.out.println("Application Name : Hotel Booking System");
        System.out.println("Version          : v1.0");

        // End message
        System.out.println("\nApplication started successfully!");
        System.out.println("Thank you for using our system.");

    }
}